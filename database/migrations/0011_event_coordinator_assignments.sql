-- Coordinator assignments for event requests (SCRUM-14).
--
-- NOTE: this table already exists in the live database — it was created
-- directly in the Supabase dashboard and never captured as a migration. Do
-- NOT re-run this file against the live DB (the plain CREATE TABLE will
-- error). It serves as a reference snapshot and for fresh environments only,
-- so migrations/ can rebuild the schema from nothing.
--
-- Reconciled against the live database on 2026-09-23 through the PostgREST
-- OpenAPI description (columns, types, nullability, defaults, primary key and
-- foreign key). Two details are deliberately faithful to live rather than to
-- what a fresh design would choose:
--
--   * coordinator_id and assigned_by are varchar(64), NOT uuid, matching the
--     max_length=64 on app/models/coordinator_assignment.py. They hold user
--     ids but carry no foreign key to auth.users, the same way staff_roles
--     treats user_id in 0010.
--   * id is an auto-incrementing integer, not a uuid. The repository's
--     definition of "current assignment" is the highest id, because
--     server-clock resolution cannot reliably order two assignments made in
--     quick succession. PostgREST reports the type but not whether live uses
--     an identity column or a serial; identity is used here as the modern
--     equivalent, and either satisfies the ordering the code depends on.

CREATE TABLE IF NOT EXISTS public.event_coordinator_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_request_id uuid NOT NULL
        REFERENCES public.event_requests (id) ON DELETE CASCADE,
    coordinator_id varchar(64) NOT NULL,
    assigned_by varchar(64) NOT NULL,
    assigned_at timestamptz NOT NULL DEFAULT now()
);

-- Serves both reads: the latest assignment for one request (id DESC), and the
-- awaiting-assignment queue's lookup of which requests are already assigned.
CREATE INDEX IF NOT EXISTS event_coordinator_assignments_request_idx
    ON public.event_coordinator_assignments (event_request_id, id DESC);

ALTER TABLE public.event_coordinator_assignments ENABLE ROW LEVEL SECURITY;

-- No policies: eventRequestService reaches this table with the secret key,
-- which bypasses RLS. Enabling it with no policy denies anon and authenticated
-- by default, so a leaked publishable key cannot read who is assigned to what.
REVOKE ALL ON public.event_coordinator_assignments FROM anon, authenticated;
GRANT SELECT, INSERT ON public.event_coordinator_assignments TO service_role;
