-- SCRUM-17: retain coordinator review outcomes and apply them atomically.
CREATE TABLE IF NOT EXISTS public.event_request_review_decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_request_id uuid NOT NULL REFERENCES public.event_requests (id),
    coordinator_id varchar NOT NULL,
    decision_status varchar NOT NULL CHECK (
        decision_status IN ('Changes Requested', 'Approved', 'Rejected')
    ),
    reason text CHECK (char_length(reason) <= 2000),
    decided_at timestamptz NOT NULL DEFAULT now(),
    organiser_response text CHECK (char_length(organiser_response) <= 2000),
    responded_at timestamptz,
    CONSTRAINT review_decision_reason_required CHECK (
        decision_status = 'Approved'
        OR nullif(btrim(reason), '') IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS event_request_review_decisions_request_idx
    ON public.event_request_review_decisions (event_request_id, decided_at DESC);

ALTER TABLE public.event_request_review_decisions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.event_request_review_decisions FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.event_request_review_decisions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.event_request_review_decisions_id_seq
    TO service_role;

CREATE OR REPLACE FUNCTION public.decide_event_request_by_coordinator(
    p_event_request_id uuid,
    p_coordinator_id varchar,
    p_decision_status varchar,
    p_reason text DEFAULT NULL
)
RETURNS public.event_requests
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_current public.event_requests%ROWTYPE;
    v_assigned_coordinator varchar;
BEGIN
    SELECT * INTO v_current
    FROM public.event_requests
    WHERE id = p_event_request_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'event request not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT coordinator_id INTO v_assigned_coordinator
    FROM public.event_coordinator_assignments
    WHERE event_request_id = p_event_request_id
    ORDER BY id DESC
    LIMIT 1;

    IF v_assigned_coordinator IS NULL
       OR v_assigned_coordinator <> p_coordinator_id THEN
        RAISE EXCEPTION 'caller is not the assigned coordinator'
            USING ERRCODE = 'P0003';
    END IF;

    IF v_current.status <> 'Under Review'
       OR p_decision_status NOT IN (
           'Changes Requested', 'Approved', 'Rejected'
       ) THEN
        RAISE EXCEPTION 'review decision not allowed from status %', v_current.status
            USING ERRCODE = 'P0004';
    END IF;

    IF p_decision_status IN ('Changes Requested', 'Rejected')
       AND nullif(btrim(p_reason), '') IS NULL THEN
        RAISE EXCEPTION 'reason required for review decision'
            USING ERRCODE = 'P0004';
    END IF;

    INSERT INTO public.event_request_review_decisions (
        event_request_id, coordinator_id, decision_status, reason
    ) VALUES (
        p_event_request_id,
        p_coordinator_id,
        p_decision_status,
        nullif(btrim(p_reason), '')
    );

    UPDATE public.event_requests
    SET status = p_decision_status
    WHERE id = p_event_request_id
    RETURNING * INTO v_current;

    RETURN v_current;
END;
$$;

REVOKE ALL ON FUNCTION public.decide_event_request_by_coordinator(
    uuid, varchar, varchar, text
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.decide_event_request_by_coordinator(
    uuid, varchar, varchar, text
) TO service_role;

CREATE OR REPLACE FUNCTION public.respond_to_event_request_clarification(
    p_event_request_id uuid,
    p_organiser_id uuid,
    p_response text
)
RETURNS public.event_request_review_decisions
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_request public.event_requests%ROWTYPE;
    v_decision public.event_request_review_decisions%ROWTYPE;
BEGIN
    SELECT * INTO v_request
    FROM public.event_requests
    WHERE id = p_event_request_id AND organiser_id = p_organiser_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'event request not found' USING ERRCODE = 'P0002';
    END IF;

    IF v_request.status <> 'Changes Requested'
       OR nullif(btrim(p_response), '') IS NULL THEN
        RAISE EXCEPTION 'clarification response not allowed'
            USING ERRCODE = 'P0004';
    END IF;

    SELECT * INTO v_decision
    FROM public.event_request_review_decisions
    WHERE event_request_id = p_event_request_id
      AND decision_status = 'Changes Requested'
    ORDER BY id DESC
    LIMIT 1
    FOR UPDATE;

    IF NOT FOUND OR v_decision.organiser_response IS NOT NULL THEN
        RAISE EXCEPTION 'clarification response not allowed'
            USING ERRCODE = 'P0004';
    END IF;

    UPDATE public.event_request_review_decisions
    SET organiser_response = btrim(p_response), responded_at = now()
    WHERE id = v_decision.id
    RETURNING * INTO v_decision;

    RETURN v_decision;
END;
$$;

REVOKE ALL ON FUNCTION public.respond_to_event_request_clarification(
    uuid, uuid, text
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.respond_to_event_request_clarification(
    uuid, uuid, text
) TO service_role;

CREATE OR REPLACE FUNCTION public.resume_event_request_review_by_coordinator(
    p_event_request_id uuid,
    p_coordinator_id varchar
)
RETURNS public.event_requests
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_request public.event_requests%ROWTYPE;
    v_decision public.event_request_review_decisions%ROWTYPE;
    v_assigned_coordinator varchar;
BEGIN
    SELECT * INTO v_request
    FROM public.event_requests
    WHERE id = p_event_request_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'event request not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT coordinator_id INTO v_assigned_coordinator
    FROM public.event_coordinator_assignments
    WHERE event_request_id = p_event_request_id
    ORDER BY id DESC
    LIMIT 1;

    IF v_assigned_coordinator IS NULL
       OR v_assigned_coordinator <> p_coordinator_id THEN
        RAISE EXCEPTION 'caller is not the assigned coordinator'
            USING ERRCODE = 'P0003';
    END IF;

    SELECT * INTO v_decision
    FROM public.event_request_review_decisions
    WHERE event_request_id = p_event_request_id
      AND decision_status = 'Changes Requested'
    ORDER BY id DESC
    LIMIT 1;

    IF v_request.status <> 'Changes Requested'
       OR v_decision.organiser_response IS NULL THEN
        RAISE EXCEPTION 'review cannot resume before organiser response'
            USING ERRCODE = 'P0004';
    END IF;

    UPDATE public.event_requests
    SET status = 'Under Review'
    WHERE id = p_event_request_id AND status = 'Changes Requested'
    RETURNING * INTO v_request;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'review status changed concurrently'
            USING ERRCODE = 'P0004';
    END IF;

    RETURN v_request;
END;
$$;

REVOKE ALL ON FUNCTION public.resume_event_request_review_by_coordinator(
    uuid, varchar
) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.resume_event_request_review_by_coordinator(
    uuid, varchar
) TO service_role;
