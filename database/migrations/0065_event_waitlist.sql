    END IF;

    IF v_entry.status = 'Closed' THEN
        RAISE EXCEPTION 'entry not found' USING ERRCODE = 'P0002';
    END IF;

    IF v_entry.status = 'Withdrawn' THEN
        RAISE EXCEPTION 'already withdrawn' USING ERRCODE = 'P0004';
    END IF;

    IF v_entry.status = 'Accepted' THEN
        -- Not a waiting-list action any more; the registration goes through
        -- withdraw_registration (AC7-N2).
        RAISE EXCEPTION 'not offered' USING ERRCODE = 'P0004';
    END IF;

    v_place := v_entry.place_id;

    UPDATE public.event_waitlist_entries
    SET status = 'Withdrawn',
        withdrawn_at = p_now,
        offered_at = NULL,
        expires_at = NULL,
        warned_at = NULL,
        place_id = NULL
    WHERE id = v_entry.id
    RETURNING * INTO v_entry;

    IF v_place IS NOT NULL THEN
        -- AC7: an active offer is cancelled and the place is handed over in
        -- this same transaction.
        UPDATE public.event_waitlist_place_offers
        SET outcome = 'Withdrawn'
        WHERE place_id = v_place AND attendee_id = p_attendee_id;

        PERFORM private.offer_open_place(v_event.id, v_place, p_now);
    END IF;

    RETURN v_entry;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.withdraw_from_waitlist(uuid, uuid, timestamptz)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.withdraw_from_waitlist(uuid, uuid, timestamptz)
    TO service_role;

CREATE OR REPLACE FUNCTION public.choose_waitlist_recipient(
    p_event_request_id uuid,
    p_entry_id uuid,
    p_coordinator_id text,
    p_now timestamptz
)
RETURNS public.event_waitlist_entries
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_event public.event_requests;
    v_entry public.event_waitlist_entries;
    v_holder public.event_waitlist_entries;
    v_place public.event_waitlist_places;
BEGIN
    SELECT * INTO v_event
    FROM public.event_requests
    WHERE id = p_event_request_id
    FOR UPDATE;

    -- The assigned Coordinator only (D9; latest row, as 0060).
    IF NOT FOUND OR v_event.status <> 'Confirmed' OR p_coordinator_id IS DISTINCT FROM (
        SELECT a.coordinator_id FROM public.event_coordinator_assignments AS a
        WHERE a.event_request_id = p_event_request_id ORDER BY a.id DESC LIMIT 1
    ) THEN
        RAISE EXCEPTION 'event not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT * INTO v_entry
    FROM public.event_waitlist_entries
    WHERE id = p_entry_id AND event_request_id = p_event_request_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'entry not found' USING ERRCODE = 'P0002';
    END IF;

    IF v_entry.status <> 'Waiting' THEN
        RAISE EXCEPTION 'not waiting' USING ERRCODE = 'P0004';
    END IF;

    SELECT * INTO v_place
    FROM public.event_waitlist_places
    WHERE event_request_id = p_event_request_id AND closed_at IS NULL
    ORDER BY opened_at
    LIMIT 1
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'no open place' USING ERRCODE = 'P0004';
    END IF;

    -- D9: revoke the automatic offer in flight for this place. The holder
    -- keeps their position (queued_at unchanged) and is told.
    SELECT * INTO v_holder
    FROM public.event_waitlist_entries
    WHERE place_id = v_place.id AND status = 'Offered'
    FOR UPDATE;

    IF FOUND THEN
        UPDATE public.event_waitlist_place_offers
        SET outcome = 'Revoked'
        WHERE place_id = v_place.id AND attendee_id = v_holder.attendee_id;

        UPDATE public.event_waitlist_entries
        SET status = 'Waiting',
            offered_at = NULL,
            expires_at = NULL,
            warned_at = NULL,
            place_id = NULL
        WHERE id = v_holder.id;

        INSERT INTO public.waitlist_notification_outbox
            (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
        VALUES (
            v_holder.id,
            v_holder.attendee_id,
            'waitlist_offer_revoked',
            'waitlist-revoked:' || v_holder.id || ':'
                || extract(epoch from v_holder.offered_at),
            jsonb_build_object('event_name', v_event.event_name),
            p_now
        );
    END IF;

    UPDATE public.event_waitlist_entries
    SET status = 'Offered',
        offered_at = p_now,
        expires_at = p_now + interval '72 hours',
        warned_at = NULL,
        place_id = v_place.id
    WHERE id = v_entry.id
    RETURNING * INTO v_entry;

    INSERT INTO public.event_waitlist_place_offers (place_id, attendee_id, outcome)
    VALUES (v_place.id, v_entry.attendee_id, 'Offered')
    ON CONFLICT (place_id, attendee_id) DO UPDATE SET outcome = 'Offered';

    INSERT INTO public.waitlist_notification_outbox
        (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
    VALUES (
        v_entry.id,
        v_entry.attendee_id,
        'waitlist_offered',
        'waitlist-offered:' || v_entry.id || ':' || extract(epoch from p_now),
        jsonb_build_object(
            'event_name', v_event.event_name,
            'expires_at', p_now + interval '72 hours'
        ),
        p_now
    );

    RETURN v_entry;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.choose_waitlist_recipient(uuid, uuid, text, timestamptz)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.choose_waitlist_recipient(uuid, uuid, text, timestamptz)
    TO service_role;

-- One timer pass: expiries (strictly after expires_at, D1), the cut-off close
-- (D11) and the 48h warnings (D2), event by event under its row lock, so two
-- instances or two passes never double-act (AC4-X1).
CREATE OR REPLACE FUNCTION public.process_waitlist_timers(p_now timestamptz)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_event record;
    v_entry public.event_waitlist_entries;
    v_start timestamptz;
BEGIN
    FOR v_event IN
        SELECT DISTINCT r.id, r.status, r.event_name, r.proposed_date_times
        FROM public.event_requests r
        JOIN public.event_waitlist_entries e ON e.event_request_id = r.id
        WHERE e.status IN ('Waiting', 'Offered')
    LOOP
        -- Lock this event in turn; the scan above did not.
        PERFORM 1 FROM public.event_requests r
        WHERE r.id = v_event.id
        FOR UPDATE;

        -- A cancelled event's entries were Closed by the D13 trigger; leave them.
        IF v_event.status <> 'Confirmed' THEN
            CONTINUE;
        END IF;

        SELECT min(d) INTO v_start FROM unnest(v_event.proposed_date_times) AS d;

        -- 1. Expiries (D1: strictly after expires_at; AC4-B4).
        FOR v_entry IN
            SELECT * FROM public.event_waitlist_entries
            WHERE event_request_id = v_event.id
              AND status = 'Offered'
              AND p_now > expires_at
            ORDER BY queued_at, seq
            FOR UPDATE
        LOOP
            UPDATE public.event_waitlist_place_offers
            SET outcome = 'Lapsed'
            WHERE place_id = v_entry.place_id
              AND attendee_id = v_entry.attendee_id
              AND outcome = 'Offered';

            INSERT INTO public.waitlist_notification_outbox
                (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
            VALUES (
                v_entry.id,
                v_entry.attendee_id,
                'waitlist_offer_expired',
                'waitlist-expired:' || v_entry.id || ':'
                    || extract(epoch from v_entry.offered_at),
                jsonb_build_object('event_name', v_event.event_name),
                p_now
            );

            IF v_start IS NOT NULL AND p_now + interval '72 hours' < v_start THEN
                -- D3: to the back of the queue with a fresh queued_at.
                UPDATE public.event_waitlist_entries
                SET status = 'Waiting',
                    queued_at = p_now,
                    offered_at = NULL,
                    expires_at = NULL,
                    warned_at = NULL,
                    place_id = NULL
                WHERE id = v_entry.id;

                PERFORM private.offer_open_place(v_event.id, v_entry.place_id, p_now);
            ELSE
                -- D11: past the cut-off the entry becomes Closed, not requeued,
                -- and the place opens to registration (D12).
                UPDATE public.event_waitlist_entries
                SET status = 'Closed',
                    closed_at = p_now,
                    offered_at = NULL,
                    expires_at = NULL,
                    warned_at = NULL,
                    place_id = NULL
                WHERE id = v_entry.id;

                UPDATE public.event_waitlist_places
                SET closed_at = p_now, outcome = 'Released'
                WHERE id = v_entry.place_id AND closed_at IS NULL;

                INSERT INTO public.waitlist_notification_outbox
                    (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
                VALUES (
                    v_entry.id,
                    v_entry.attendee_id,
                    'waitlist_closed',
                    'waitlist-closed:' || v_entry.id || ':' || extract(epoch from p_now),
                    jsonb_build_object('event_name', v_event.event_name),
                    p_now
                );
            END IF;
        END LOOP;

        -- 2. The cut-off close (D11): every Waiting entry closes exactly at
        -- start - 72h (AC10-B1..B2) with one notice each.
        IF v_start IS NOT NULL AND p_now >= v_start - interval '72 hours' THEN
            FOR v_entry IN
                SELECT * FROM public.event_waitlist_entries
                WHERE event_request_id = v_event.id AND status = 'Waiting'
                ORDER BY queued_at, seq
                FOR UPDATE
            LOOP
                UPDATE public.event_waitlist_entries
                SET status = 'Closed', closed_at = p_now
                WHERE id = v_entry.id;

                INSERT INTO public.waitlist_notification_outbox
                    (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
                VALUES (
                    v_entry.id,
                    v_entry.attendee_id,
                    'waitlist_closed',
                    'waitlist-closed:' || v_entry.id || ':' || extract(epoch from p_now),
                    jsonb_build_object('event_name', v_event.event_name),
                    p_now
                );
            END LOOP;
        END IF;

        -- 3. Warnings (D2: one, at offered_at + 48h, never repeated).
        FOR v_entry IN
            SELECT * FROM public.event_waitlist_entries
            WHERE event_request_id = v_event.id
              AND status = 'Offered'
              AND warned_at IS NULL
              AND p_now >= offered_at + interval '48 hours'
            ORDER BY queued_at, seq
            FOR UPDATE
        LOOP
            INSERT INTO public.waitlist_notification_outbox
                (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
            VALUES (
                v_entry.id,
                v_entry.attendee_id,
                'waitlist_offer_expiring',
                'waitlist-expiring:' || v_entry.id || ':'
                    || extract(epoch from v_entry.offered_at),
                jsonb_build_object(
                    'event_name', v_event.event_name,
                    'expires_at', v_entry.expires_at
                ),
                p_now
            );

            UPDATE public.event_waitlist_entries
            SET warned_at = p_now
            WHERE id = v_entry.id;
        END LOOP;
    END LOOP;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.process_waitlist_timers(timestamptz)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.process_waitlist_timers(timestamptz)
    TO service_role;

-- ---------------------------------------------------------------------------
-- D13: cancelling the event closes every Waiting/Offered entry with one
-- notice each (AC12), in the same transaction as the status change. The
-- trigger is private: it runs only after an authorised event UPDATE and
-- cannot be called directly.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION private.close_waitlist_on_cancel()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_entry public.event_waitlist_entries;
BEGIN
    IF NEW.status IS DISTINCT FROM 'Cancelled' THEN
        RETURN NEW;
    END IF;

    FOR v_entry IN
        SELECT * FROM public.event_waitlist_entries
        WHERE event_request_id = NEW.id AND status IN ('Waiting', 'Offered')
        ORDER BY queued_at, seq
        FOR UPDATE
    LOOP
        UPDATE public.event_waitlist_entries
        SET status = 'Closed',
            closed_at = now(),
            offered_at = NULL,
            expires_at = NULL,
            warned_at = NULL,
            place_id = NULL
        WHERE id = v_entry.id;

        INSERT INTO public.waitlist_notification_outbox
            (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
        VALUES (
            v_entry.id,
            v_entry.attendee_id,
            'waitlist_event_cancelled',
            'waitlist-cancelled:' || v_entry.id || ':' || extract(epoch from now()),
            jsonb_build_object('event_name', NEW.event_name),
            now()
        );
    END LOOP;

    RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION private.close_waitlist_on_cancel()
    FROM PUBLIC, anon, authenticated, service_role;

DROP TRIGGER IF EXISTS scrum24_waitlist_event_cancelled ON public.event_requests;
CREATE TRIGGER scrum24_waitlist_event_cancelled
    AFTER UPDATE OF status ON public.event_requests
    FOR EACH ROW
    EXECUTE FUNCTION private.close_waitlist_on_cancel();
