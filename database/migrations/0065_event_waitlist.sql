CREATE OR REPLACE FUNCTION public.accept_waitlist_offer(
    p_entry_id uuid,
    p_attendee_id uuid,
    p_now timestamptz
)
RETURNS public.event_waitlist_entries
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_event public.event_requests;
    v_entry public.event_waitlist_entries;
    v_place uuid;
BEGIN
    -- The event lock first (the shared lock order), through the entry's event.
    SELECT * INTO v_event
    FROM public.event_requests
    WHERE id = (
        SELECT e.event_request_id FROM public.event_waitlist_entries e
        WHERE e.id = p_entry_id AND e.attendee_id = p_attendee_id
    )
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'entry not found' USING ERRCODE = 'P0002';
    END IF;

    IF v_event.status <> 'Confirmed' THEN
        RAISE EXCEPTION 'entry not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT * INTO v_entry
    FROM public.event_waitlist_entries
    WHERE id = p_entry_id AND attendee_id = p_attendee_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'entry not found' USING ERRCODE = 'P0002';
    END IF;

    IF v_entry.status = 'Closed' THEN
        RAISE EXCEPTION 'entry not found' USING ERRCODE = 'P0002';
    END IF;

    IF v_entry.status <> 'Offered' THEN
        RAISE EXCEPTION 'not offered' USING ERRCODE = 'P0004';
    END IF;

    -- D1: the window is inclusive; only strictly after expires_at is it gone.
    IF p_now > v_entry.expires_at THEN
        RAISE EXCEPTION 'offer expired' USING ERRCODE = 'P0004';
    END IF;

    -- The offer already held the place (D6), so no capacity re-check: the
    -- registration and the Accepted entry commit together (AC4-H1).
    v_place := v_entry.place_id;

    INSERT INTO public.event_registrations (event_request_id, attendee_id)
    VALUES (v_event.id, p_attendee_id);

    UPDATE public.event_waitlist_entries
    SET status = 'Accepted',
        offered_at = NULL,
        expires_at = NULL,
        warned_at = NULL,
        place_id = NULL
    WHERE id = v_entry.id
    RETURNING * INTO v_entry;

    UPDATE public.event_waitlist_place_offers
    SET outcome = 'Accepted'
    WHERE place_id = v_place AND attendee_id = p_attendee_id;

    UPDATE public.event_waitlist_places
    SET closed_at = p_now, outcome = 'Accepted'
    WHERE id = v_place;

    RETURN v_entry;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.accept_waitlist_offer(uuid, uuid, timestamptz)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.accept_waitlist_offer(uuid, uuid, timestamptz)
    TO service_role;

CREATE OR REPLACE FUNCTION public.withdraw_from_waitlist(
    p_entry_id uuid,
    p_attendee_id uuid,
    p_now timestamptz
