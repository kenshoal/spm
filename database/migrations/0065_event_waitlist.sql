-- Event waiting list (SCRUM-24). Safe to re-run. Needs 0048, 0060 and 0062.
--
-- When a Confirmed event is full, an Attendee can join its waiting list. Each
-- place that opens is held for the next eligible Attendee for 72 hours (D1):
-- they are told when it is offered, warned 24h before it expires (D2) and told
-- when it does. An expired offeree goes to the back of the queue (D3). Each
-- place keeps an offer history: a place is never re-offered to someone who let
-- it lapse (D7); a revoked holder may take the same place again. A pending
-- offer holds its place against every capacity check (D6), through the shared
-- helper private.places_taken. New offers stop at the #116 cut-off
-- (start - 72h, strict; D8); from the cut-off the list is Closed (D11) and a
-- place freed after it opens to normal registration (D12). Cancelling the
-- event closes every entry with one notice each (D13).
--
-- Notices are written to waitlist_notification_outbox inside the same
-- transaction and delivered after commit by the service relay (the SCRUM-64
-- 0037/0038 pattern), so a rollback sends nothing and an outage never undoes
-- the change.
--
-- Lock protocol: every function takes the event_requests row FOR UPDATE first
-- (the 0048 lock) and only then the entry/place rows, so a withdrawal, a
-- registration, an accept and a timer pass all serialise on the event.
-- process_waitlist_timers locks each event in turn and is idempotent.
--
-- The public functions are SECURITY DEFINER with an empty search path (as in
-- 0060): they must write the private history and outbox rows, and the private
-- helpers stay non-callable, so an invoker body could not call them. The
-- private schema holds the helpers, the D7 history helpers' triggers and the
-- D13 cancellation trigger; EXECUTE is revoked even from service_role.
--
-- Positions are never stored: they are the row_number of the Waiting entries
-- ordered by queued_at, seq, so a withdrawal closes the gap automatically
-- (AC6-H1).

CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS public.event_waitlist_places (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    event_request_id uuid NOT NULL
        REFERENCES public.event_requests (id) ON DELETE CASCADE,
    opened_at timestamptz NOT NULL DEFAULT now(),
    closed_at timestamptz,
    outcome text CHECK (outcome IN ('Accepted', 'Released')),
    CONSTRAINT event_waitlist_places_closed_check CHECK (
        (closed_at IS NULL) = (outcome IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.event_waitlist_entries (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    seq bigint GENERATED BY DEFAULT AS IDENTITY,
    event_request_id uuid NOT NULL
        REFERENCES public.event_requests (id) ON DELETE CASCADE,
    attendee_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'Waiting'
        CHECK (status IN ('Waiting', 'Offered', 'Accepted', 'Withdrawn', 'Closed')),
    queued_at timestamptz NOT NULL DEFAULT now(),
    offered_at timestamptz,
    expires_at timestamptz,
    warned_at timestamptz,
    withdrawn_at timestamptz,
    closed_at timestamptz,
    place_id uuid REFERENCES public.event_waitlist_places (id),
    -- The offer fields move with the status (as 0062 keeps withdrawn_at in step).
    CONSTRAINT event_waitlist_entries_offered_check CHECK (
        (status = 'Offered') = (
            offered_at IS NOT NULL AND expires_at IS NOT NULL AND place_id IS NOT NULL
        )
    ),
    CONSTRAINT event_waitlist_entries_withdrawn_check CHECK (
        (status = 'Withdrawn') = (withdrawn_at IS NOT NULL)
    ),
    CONSTRAINT event_waitlist_entries_closed_check CHECK (
        (status = 'Closed') = (closed_at IS NOT NULL)
    )
);

-- One active (Waiting or Offered) entry per attendee per event (AC1-P1..P2).
CREATE UNIQUE INDEX IF NOT EXISTS event_waitlist_entries_one_active_idx
    ON public.event_waitlist_entries (event_request_id, attendee_id)
    WHERE status IN ('Waiting', 'Offered');
-- FIFO order for the offer pass.
CREATE INDEX IF NOT EXISTS event_waitlist_entries_queue_idx
    ON public.event_waitlist_entries (event_request_id, status, queued_at, seq);


-- D7's per-place memory: who has been offered this place, and how it ended.
CREATE TABLE IF NOT EXISTS public.event_waitlist_place_offers (
    place_id uuid NOT NULL
        REFERENCES public.event_waitlist_places (id) ON DELETE CASCADE,
    attendee_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    outcome text NOT NULL
        CHECK (outcome IN ('Offered', 'Lapsed', 'Revoked', 'Withdrawn', 'Accepted')),
    PRIMARY KEY (place_id, attendee_id)
);

CREATE TABLE IF NOT EXISTS public.waitlist_notification_outbox (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    entry_id uuid NOT NULL
