    FROM PUBLIC, anon, authenticated, service_role;

-- Offer one open place to the earliest eligible Waiting attendee (AC2, D7).
-- The caller holds the event row lock. D8: a new offer is issued only if its
-- 72h window ends before the event starts (strict, #116); otherwise — and when
-- nobody is eligible — the place is released to registration at once (D12).
CREATE OR REPLACE FUNCTION private.offer_open_place(
    p_event_request_id uuid,
    p_place_id uuid,
    p_now timestamptz
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_event public.event_requests;
    v_entry public.event_waitlist_entries;
    v_start timestamptz;
BEGIN
    SELECT * INTO v_event
    FROM public.event_requests
    WHERE id = p_event_request_id;

    SELECT min(d) INTO v_start FROM unnest(v_event.proposed_date_times) AS d;

    SELECT * INTO v_entry
    FROM public.event_waitlist_entries AS e
    WHERE e.event_request_id = p_event_request_id
      AND e.status = 'Waiting'
      -- D7: only a lapsed place is never theirs again; a revoked holder is
      -- eligible for the same place (AC3-H2).
      AND NOT EXISTS (
            SELECT 1 FROM public.event_waitlist_place_offers po
            WHERE po.place_id = p_place_id
              AND po.attendee_id = e.attendee_id
              AND po.outcome = 'Lapsed'
      )
    ORDER BY e.queued_at, e.seq
    LIMIT 1
    FOR UPDATE OF e;

    IF NOT FOUND THEN
        UPDATE public.event_waitlist_places
        SET closed_at = p_now, outcome = 'Released'
        WHERE id = p_place_id AND closed_at IS NULL;
        RETURN;
    END IF;

    IF v_start IS NULL OR NOT (p_now + interval '72 hours' < v_start) THEN
        UPDATE public.event_waitlist_places
        SET closed_at = p_now, outcome = 'Released'
        WHERE id = p_place_id AND closed_at IS NULL;
        RETURN;
    END IF;

    UPDATE public.event_waitlist_entries
    SET status = 'Offered',
        offered_at = p_now,
        expires_at = p_now + interval '72 hours',
        place_id = p_place_id
    WHERE id = v_entry.id;

    INSERT INTO public.event_waitlist_place_offers (place_id, attendee_id, outcome)
    VALUES (p_place_id, v_entry.attendee_id, 'Offered')
    ON CONFLICT (place_id, attendee_id) DO UPDATE SET outcome = 'Offered';

    INSERT INTO public.waitlist_notification_outbox
        (entry_id, recipient_id, event_type, idempotency_key, payload, occurred_at)
    VALUES (
        v_entry.id,
        v_entry.attendee_id,
        'waitlist_offered',
        'waitlist-offered:' || v_entry.id || ':' || extract(epoch from p_now),
        jsonb_build_object(
            'event_name', v_event.event_name,
            'expires_at', p_now + interval '72 hours'
        ),
        p_now
    );
END;
$$;

REVOKE EXECUTE ON FUNCTION private.offer_open_place(uuid, uuid, timestamptz)
    FROM PUBLIC, anon, authenticated, service_role;

-- Open a fresh place for a freed registration place and offer it (AC2).
-- Called from withdraw_registration after its UPDATE, once the place is free.
CREATE OR REPLACE FUNCTION private.open_place(
    p_event_request_id uuid,
    p_now timestamptz
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_place uuid;
BEGIN
    INSERT INTO public.event_waitlist_places (event_request_id, opened_at)
    VALUES (p_event_request_id, p_now)
    RETURNING id INTO v_place;

    PERFORM private.offer_open_place(p_event_request_id, v_place, p_now);

    RETURN v_place;
END;
$$;

