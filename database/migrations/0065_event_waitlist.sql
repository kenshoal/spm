CREATE OR REPLACE FUNCTION private.places_taken(p_event_request_id uuid)
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT (
        (SELECT count(*) FROM public.event_registrations
          WHERE event_request_id = p_event_request_id AND status = 'Registered')
      + (SELECT count(*) FROM public.event_waitlist_entries
          WHERE event_request_id = p_event_request_id AND status = 'Offered')
    )::integer
$$;

