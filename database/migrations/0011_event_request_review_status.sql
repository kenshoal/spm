-- Allow the agreed request lifecycle without changing who may write each transition.
-- The API still checks actor, assignment, and expected prior status.
ALTER TABLE public.event_requests
    DROP CONSTRAINT IF EXISTS event_requests_status_check;

ALTER TABLE public.event_requests
    ADD CONSTRAINT event_requests_status_check CHECK (status IN (
        'Draft', 'Submitted', 'Under Review', 'Changes Requested', 'Approved',
        'Planning', 'Confirmed', 'Completed', 'Cancelled', 'Rejected'
    ));

-- SCRUM-14 created this table directly in the shared database. Capture its
-- existing shape for fresh environments and close direct client access;
-- eventRequestService writes through its server-only secret key.
CREATE TABLE IF NOT EXISTS public.event_coordinator_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_request_id uuid NOT NULL REFERENCES public.event_requests (id),
    coordinator_id varchar NOT NULL,
    assigned_by varchar NOT NULL,
    assigned_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.event_coordinator_assignments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.event_coordinator_assignments FROM anon, authenticated;
GRANT SELECT, INSERT ON public.event_coordinator_assignments TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.event_coordinator_assignments_id_seq TO service_role;
